import numpy as np
import matplotlib.pyplot as plt

# Entradas, pesos e bias do exemplo do artigo
x = np.array([5.1, 3.5, 1.4, 0.2])
w = np.array([1.0, 0.0, 0.5, -0.3])
b = 0.5

# Produto escalar mais bias
z = np.dot(w, x) + b

# Funções de ativação
def sigmoide(z):
    return 1 / (1 + np.exp(-z))

def tanh(z):
    return np.tanh(z)

def relu(z):
    return np.maximum(0, z)

print(f"Soma ponderada: {z:.2f}")
print(f"Sigmoide: {sigmoide(z):.6f}")
print(f"Tanh: {tanh(z):.6f}")
print(f"ReLU: {relu(z):.2f}")

# Valores para desenhar as curvas
valores_z = np.linspace(-8, 8, 500)

funcoes = [
    ("Sigmoide", sigmoide),
    ("Tanh", tanh),
    ("ReLU", relu)
]

fig, eixos = plt.subplots(1, 3, figsize=(12, 4))

for eixo, (nome, funcao) in zip(eixos, funcoes):
    eixo.plot(valores_z, funcao(valores_z))
    eixo.scatter(z, funcao(z), color="red", label="z = 6,24")
    eixo.set_title(nome)
    eixo.set_xlabel("Soma ponderada z")
    eixo.set_ylabel("Saída")
    eixo.grid(True, alpha=0.3)
    eixo.legend()

plt.tight_layout()
plt.show()